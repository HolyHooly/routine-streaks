		'}',
		'',
		'function routineStatusPillLabel(settings, routine, cache) {',
		'  const weeklyLabel = weeklyProgressLabel(settings, routine);',
		'  return weeklyLabel.length > 0 ? weeklyLabel : statusLabel(cache.todayStatus);',
		'}',
		'',
		'function routineScheduleTypeLabel(settings, routine) {',
		'  const summary = exportedRoutineSummary(settings, routine);',
		'  if (typeof summary.scheduleTypeLabel === "string" && summary.scheduleTypeLabel.length > 0) return summary.scheduleTypeLabel;',
		'  const type = routine && routine.schedule ? routine.schedule.type : "weekdays";',
		'  if (type === "weekly_count") return "Weekly";',
		'  if (type === "interval") return "Interval";',
		'  return "Weekdays";',
		'}',
		'',
		'function enabledRoutines(settings) {',
		'  return (settings.routines || []).filter(function (routine) {',
		'    return routine.enabled !== false;',
		'  });',
		'}',
		'',
		'function requiredToday(settings, routines) {',
		'  const ids = exportedTodaySummary(settings).requiredRoutineIds;',
		'  return ids.map(function (id) {',
		'    return routines.find(function (routine) {',
		'      return routine.id === id;',
		'    });',
		'  }).filter(Boolean);',
		'}',
		'',
		'function todaySummary(settings) {',
		'  const summary = exportedTodaySummary(settings);',
		'  return {',
		'    required: requiredToday(settings, enabledRoutines(settings)),',
		'    requiredCount: summary.requiredCount,',
		'    completed: summary.completed,',
		'    incomplete: summary.incomplete,',
		'    allDone: summary.allDone,',
		'  };',
		'}',
		'',
		'function bestCurrentStreak(settings) {',
		'  return exportedTodaySummary(settings).bestCurrentStreak;',
		'}',
		'',
		'function selectedWidgetType(settings) {',
		'  const type = GENERATED_WIDGET_TYPE || settings.scriptableWidgetType || "dashboard";',
		'  const allowed = ["dashboard", "overview", "pet", "routine_cards", "today_items", "routine_focus"];',
		'  return allowed.indexOf(type) >= 0 ? type : "dashboard";',
		'}',
		'',
		'function selectedRoutine(settings, routines) {',
		'  const id = GENERATED_ROUTINE_ID || settings.scriptableRoutineId || "";',
		'  return routines.find(function (routine) {',
		'    return routine.id === id;',
		'  }) || routines[0] || null;',
		'}',
		'',
		'function selectedTodayRoutines(settings, routines) {',
		'  const ids = GENERATED_TODAY_ROUTINE_IDS.length > 0 ? GENERATED_TODAY_ROUTINE_IDS : settings.scriptableTodayRoutineIds || [];',
		'  const selected = ids.map(function (id) {',
		'    return routines.find(function (routine) {',
		'      return routine.id === id;',
		'    });',
		'  }).filter(Boolean);',
		'  const fallback = requiredToday(settings, routines);',
		'  const source = selected.length > 0 ? selected : fallback;',
		'  const max = FAMILY === "small" ? 1 : 4;',
		'  return source.slice(0, max);',
		'}',
		'',
		'function statusLabel(status) {',
		'  if (status === "complete") return "Done";',
		'  if (status === "incomplete") return "Open";',
		'  if (status === "missing_daily_note") return "Missing note";',
		'  if (status === "no_tasks") return "No tasks";',
		'  if (status === "frozen") return "Frozen";',
		'  if (status === "off_schedule") return "Rest";',
		'  if (status === "stale") return "Needs sync";',
		'  return "Idle";',
		'}',
		'',
		'function statusColor(status) {',
		'  if (status === "complete") return COLORS.success;',
		'  if (status === "incomplete" || status === "missing_daily_note" || status === "no_tasks" || status === "stale") return COLORS.warning;',
		'  if (status === "frozen") return COLORS.accent;',
		'  return COLORS.faint;',
		'}',
		'',
		'function petMood(allDone) {',
		'  return allDone ? "happy" : "angry";',
		'}',
		'',
		'function createPetImage(pet, mood) {',
		'  const context = new DrawContext();',
		'  context.size = new Size(64, 64);',
		'  context.opaque = false;',
		'  context.respectScreenScale = false;',
		'',
		'  if (pet === "cat") {',
		'    drawCatPixelArt(context, mood);',
		'  } else if (pet === "parrot") {',
		'    drawParrotPixelArt(context, mood);',
		'  } else {',
		'    drawDogPixelArt(context, mood);',
		'  }',
		'',
		'  return context.getImage();',
		'}',
		'',
		'function addPetImage(container, settings, allDone, size) {',
		'  const pet = settings.overviewPet || "dog";',
		'  const image = container.addImage(createPetImage(pet, petMood(allDone)));',
		'  image.imageSize = new Size(size, size);',
		'  return image;',
		'}',
		'',

		'  drawPixelRect(context, 20, 31, 24, 16, c.muzzle);',
		'  drawPixelRect(context, 24, 35, 16, 14, c.white);',
		'  drawPixelRect(context, 30, 34, 4, 4, c.eye);',
		'',
		'  if (angry) {',
		'    drawPixelRect(context, 21, 24, 9, 3, c.warning);',
		'    drawPixelRect(context, 35, 24, 9, 3, c.warning);',

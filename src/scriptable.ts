		'',
		'function exportedRoutineSummary(settings, routine) {',
		'  const summary = settings.todaySummary || {};',
		'  const routines = Array.isArray(summary.routines) ? summary.routines : [];',
		'  return routines.find(function (candidate) {',
		'    return candidate && candidate.id === routine.id;',
		'  }) || {};',
		'}',
		'',

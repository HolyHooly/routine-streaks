		'    drawPixelRect(context, 25, 43, 14, 3, c.mouth);',
		'    drawPixelRect(context, 24, 44, 4, 3, c.mouth);',
		'    drawPixelRect(context, 36, 44, 4, 3, c.mouth);',
		'  } else {',
		'    drawPixelRect(context, 23, 25, 5, 5, c.eye);',
		'    drawPixelRect(context, 37, 25, 5, 5, c.eye);',
		'    drawPixelRect(context, 26, 43, 12, 3, c.mouth);',
		'    drawPixelRect(context, 28, 46, 8, 4, c.blush);',
		'  }',
		'',
		'  drawPixelRect(context, 16, 33, 4, 3, c.blush);',
		'  drawPixelRect(context, 44, 33, 4, 3, c.blush);',

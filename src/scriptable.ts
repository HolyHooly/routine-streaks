		'  if (family === "small" || family === "medium" || family === "large") return family;',
		'  if (family === "accessoryRectangular" || family === "accessoryInline" || family === "accessoryCircular") return "small";',
		'  return "medium";',
		'}',
		'',
		'function setFamily(family) {',
		'  FAMILY = normalizeFamily(family);',
		'  MAX_ROUTINES = FAMILY === "large" ? 8 : FAMILY === "small" ? 2 : 4;',
		'  MAX_TASKS = FAMILY === "large" ? 8 : FAMILY === "small" ? 2 : 5;',
		'}',
		'',
		'setFamily(config.runsInWidget ? config.widgetFamily || GENERATED_WIDGET_FAMILY : GENERATED_WIDGET_FAMILY);',
		'',
		'const COLORS = {',
		'  backgroundTop: "#111827",',
		'  backgroundBottom: "#24213f",',
		'  card: "#1f2937",',
		'  text: "#f9fafb",',
		'  muted: "#9ca3af",',
		'  faint: "#6b7280",',
		'  success: "#86efac",',
		'  warning: "#fca5a5",',
		'  accent: "#fbbf24",',
		'  line: "#374151",',
		'};',
		'',
		'const PET_COLORS = {',
		'  blush: "#f49ab0",',
		'  cat: "#8f9aa7",',
		'  catDark: "#687482",',
		'  dog: "#c78342",',
		'  dogDark: "#90572d",',
